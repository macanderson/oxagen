// Agent identity + versioning (spec §6, agent-runtime epic).
export const agents = agentSchema.table(
  "agents",
  {
    ...idMixin("agt"),
    ...auditMixin(),
    ...orgScopeMixin(),
    ...softDeleteMixin(),
    slug: citext("slug").notNull(),
    name: text("name").notNull(),
    description: text("description"),
    agentType: text("agent_type").notNull(),
    activeVersionId: uuid("active_version_id"),
    // status: text + check per spec §6
    status: text("status").notNull().default("draft"),
    // deploymentStatus is the deploy on/off toggle, distinct from the
    // draft/active/archived authoring lifecycle in `status`.
    deploymentStatus: text("deployment_status").notNull().default("inactive"),
    // Nullable avatar. Either an https:// URL or the platform designed-avatar
    // spec string "avatar:v1:<json>" ({emoji,bg,mode}); capped at 512 chars at
    // the contract layer. Same column name as users/organizations for
    // consistency, even though it may carry the spec string, not a plain URL.
    avatarUrl: text("avatar_url"),
    // LLM-inferred, plain-text (<=256 char) description of what this agent does,
    // derived from its config (name/instructions/tools/triggers). Regenerated by
    // agent.definition.summarize when stale.
    summary: text("summary"),
    // SHA-256 of the canonical version config `summary` was derived from (same
    // canonicalization as agent_versions.checksum). When it no longer matches the
    // current config, the summary is stale and gets regenerated.
    summaryChecksum: text("summary_checksum"),
    // The agent's IAM identity (iam.principals kind='agent'), provisioned once
    // at agent.definition.create and soft-deleted together with the agent
    // (docs/specs/agent-rbac/spec.md §3.1: one principal per agent IDENTITY,
    // not per version/run). App-enforced — no FK across the agent/iam schema
    // boundary per CLAUDE.md storage rules.
    principalId: uuid("principal_id"),
  },
  (t) => ({
    // NON-partial on purpose: covers soft-deleted rows too, so a slug a
    // workspace has ever used is PERMANENTLY reserved (never recycled), like an
    // npm package name. Immutability of the live slug is enforced by the
    // agents_slug_immutable trigger; this index reserves it past deletion.
    // (ADR-024, migration 20260709130000_agent_slug_no_recycle.)
    workspaceSlugUniq: uniqueIndex("agents_workspace_slug_uniq").on(
      t.workspaceId,
      t.slug,
    ),
    orgIdx: index("agents_org_idx").on(t.orgId, t.workspaceId),
    deploymentStatusIdx: index("agents_deployment_status_idx").on(
      t.orgId,
      t.workspaceId,
      t.deploymentStatus,
    ),
    // Resolve the owning agent from its principal (soft-delete-on-archive path).
    principalIdx: index("agents_principal_idx").on(t.principalId),
    statusCheck: check(
      "agents_status_check",
      sql`${t.status} IN ('draft', 'active', 'archived')`,
    ),
    deploymentStatusCheck: check(
      "agents_deployment_status_check",
      sql`${t.deploymentStatus} IN ('inactive', 'active')`,
    ),
    slugCheck: check(
      "agents_slug_check",
      sql`${t.slug} ~ '^[a-z0-9]+(-[a-z0-9]+)*$'`,
    ),
  }),
);

// Agent triggers: how a deployed agent is invoked — manual, scheduled (cron),
// or by an external event. connectionId references a connected source
// (app-enforced; no cross-schema FK per CLAUDE.md storage rules).
export const agentTriggers = agentSchema.table(
  "agent_triggers",
  {
    ...idMixin("atr"),
    ...auditMixin(),
    ...orgScopeMixin(),
    ...softDeleteMixin(),
    agentId: uuid("agent_id")
      .notNull()
      .references(() => agents.id),
    triggerType: text("trigger_type").notNull(),
    // eventSource/eventType are null for manual/schedule triggers.
    eventSource: text("event_source"),
    eventType: text("event_type"),
    connectionId: uuid("connection_id"),
    // filter scopes event triggers, e.g. { branches: [...], pathGlobs: [...] }.
    filter: jsonb("filter").notNull().default(sql`'{}'::jsonb`),
    // schedule is a cron expression; null unless triggerType = 'schedule'.
    schedule: text("schedule"),
    enabled: boolean("enabled").notNull().default(false),
  },
  (t) => ({
    agentIdx: index("agent_triggers_agent_idx").on(t.agentId),
    orgIdx: index("agent_triggers_org_idx").on(t.orgId, t.workspaceId),
    typeEnabledIdx: index("agent_triggers_type_enabled_idx").on(
      t.triggerType,
      t.enabled,
    ),
    triggerTypeCheck: check(
      "agent_triggers_trigger_type_check",
      sql`${t.triggerType} IN ('manual', 'schedule', 'event')`,
    ),
  }),
);

// Immutable version snapshots. INSERT-only once published; no updatedAt by design.
export const agentVersions = agentSchema.table(
  "agent_versions",
  {
    id: uuid("id").primaryKey().default(uuidv7Default),
    agentId: uuid("agent_id")
      .notNull()
      .references(() => agents.id),
    version: integer("version").notNull(),
    isPublished: boolean("is_published").notNull().default(false),
    // checksum: SHA-256 over canonical config — immutability contract.
    checksum: text("checksum"),
    config: jsonb("config").notNull().default(sql`'{}'::jsonb`),
    createdByUserId: uuid("created_by_user_id").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .notNull()
      .defaultNow(),
    // No updatedAt by design — INSERT-only once published.
  },
  (t) => ({
    agentVersionUniq: uniqueIndex("agent_versions_agent_version_uniq").on(
      t.agentId,
      t.version,
    ),
    agentIdx: index("agent_versions_agent_idx").on(t.agentId),
  }),
);

// Skills (spec §6, agent-runtime epic). Logical identity + immutable
// versions, mirroring the agents/tools/playbooks versioning pattern.
