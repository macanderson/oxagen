-- Widen the tacho.sessions runtime CHECK: add 'cursor'.
--
-- Cursor is a wrapped harness (ADR-078 harness tier): its preToolUse hook fires
-- before every tool type and a deny answer blocks the call, so tacho-hook wraps
-- it the same way it wraps Claude Code and Codex. Without a cursor member here
-- the collector would have to ship a Cursor session as runtime = 'custom',
-- harness = 'cursor', and the fleet page could not tell a Cursor session from a
-- custom agent without reading the free-text harness.
--
-- The list is generated from TACHO_RUNTIMES in packages/database/src/schema/tacho.ts
-- (mirrored by packages/tacho/src/envelope.ts); schema/tacho.test.ts holds the
-- LATEST migration that redefines this constraint to that list, so any future
-- widening is a new migration that DROPs and re-ADDs the whole constraint.
--
-- Additive only: every value the old constraint accepted is still accepted, so
-- a plain ADD CONSTRAINT validates against existing rows without failing.
-- DROP + re-ADD keeps the operation replayable on a clean database. Atlas
-- tracks idempotency via atlas.sum -- do NOT edit this file after it is applied.

ALTER TABLE "tacho"."sessions" DROP CONSTRAINT IF EXISTS "tacho_sessions_runtime_check";
ALTER TABLE "tacho"."sessions" ADD CONSTRAINT "tacho_sessions_runtime_check"
  CHECK ("runtime" IN ('claude-code', 'claude-agent-sdk', 'custom', 'stella', 'proxy', 'codex', 'cursor'));
