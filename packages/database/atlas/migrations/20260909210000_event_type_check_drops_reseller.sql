-- Narrow the security_events event_type CHECK: drop the five billing.reseller_* values.
--
-- Oxagen sells direct to the enterprise team that runs the agents. The reseller
-- re-bill subsystem is deleted, so nothing can emit
-- billing.reseller_customer_changed, billing.reseller_price_plan_changed,
-- billing.reseller_attribution_rule_changed, billing.reseller_stripe_configured
-- or billing.reseller_rebill_pushed ever again.
--
-- This migration is dated AFTER 20260909200200_model_credential_security_events,
-- and that ordering is the whole point. The event_type CHECK is a shared cell:
-- every migration that touches it DROPs and re-ADDs the entire constraint, and
-- security-event-types.test.ts holds the LATEST such migration byte-identical to
-- generateEventTypeCheckClause(). Two branches can each write a correct
-- constraint and compose into a wrong one -- this branch removed five values
-- while #2807 added two, and whichever sorts last wins for the whole taxonomy.
-- The constraint below is regenerated from the MERGED taxonomy: #2807's
-- model-credential types included, the reseller five gone.
--
-- The taxonomy source of truth is packages/compliance/src/security-event-types.ts
-- and this constraint body was generated from it via generateEventTypeCheckClause()
-- (see db-check.ts) -- do not hand-edit the list.
--
-- NOT VALID, and this is the first migration here that needs it. Every previous
-- event_type migration only ever WIDENED the constraint, so none could conflict
-- with a row already in the table. This one narrows it, and security_events is
-- append-only audit history: a database that recorded a real reseller mutation
-- holds a row the new constraint rejects, and a plain ADD CONSTRAINT would
-- validate the whole table and fail the migration outright. NOT VALID enforces
-- every future insert while leaving recorded history intact, which is the
-- behaviour an audit table wants -- past events stay true, and the retired
-- vocabulary cannot be written again.
--
-- Strategy: DROP + re-ADD so the operation is idempotent and safe to replay on a
-- clean database. security_events is RANGE-partitioned on occurred_at; altering
-- the parent propagates the CHECK to every child partition. Atlas tracks
-- idempotency via the atlas.sum checksum -- do NOT edit this file after it is
-- applied.

ALTER TABLE "security"."security_events" DROP CONSTRAINT IF EXISTS "security_events_event_type_check";
ALTER TABLE "security"."security_events" ADD CONSTRAINT "security_events_event_type_check"
