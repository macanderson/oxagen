// ── O(1) lookup helpers ───────────────────────────────────────────────────────

const COUNTRY_CODE_SET: ReadonlySet<string> = new Set(
  COUNTRY_OPTIONS.map((c) => c.value.toUpperCase()),
);

const US_STATE_CODE_SET: ReadonlySet<string> = new Set(
  US_STATE_OPTIONS.map((s) => s.value.toUpperCase()),
);

/** True if `code` is a valid ISO 3166-1 alpha-2 country code (case-insensitive). */
export function isValidCountryCode(code: string): boolean {
  return COUNTRY_CODE_SET.has(code.toUpperCase());
}

/** True if `code` is a valid 2-letter US state / DC code (case-insensitive). */
export function isValidUsStateCode(code: string): boolean {
  return US_STATE_CODE_SET.has(code.toUpperCase());
}
