/** ISO 3166-1 alpha-2 country code (uppercase, e.g. "US"). */
export interface CountryOption {
  /** ISO 3166-1 alpha-2, uppercase (e.g. "US"). */
  value: string;
  /** Common English country name. */
  label: string;
}

/** Geographic subdivision code (e.g. ISO 3166-2 2-letter US state code). */
export interface RegionOption {
  /** ISO 3166-2 subdivision code (2-letter for US, e.g. "CA"). */
  value: string;
  /** Full subdivision name. */
  label: string;
}

